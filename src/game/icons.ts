export const ICONS: Record<ItemId | 'coin', string[]> = { ...BASE, ...MORE } as Record<ItemId | 'coin', string[]>

const cache = new Map<string, string>()
/** for things with no drawn icon (the furniture of round 11): a little picture of the model itself, set up by the UI */
let modelIcon: ((id: ItemId) => string | null) | null = null
export function setModelIcons(f: (id: ItemId) => string | null) { modelIcon = f }
export const hasDrawnIcon = (id: ItemId | 'coin') => !!ICONS[id]
/** the icon as an image URL (browser only) */
export function iconUrl(id: ItemId | 'coin'): string {
  let url = cache.get(id)
  if (url) return url
  if (!ICONS[id] && id !== 'coin' && modelIcon) {
    const m = modelIcon(id)
    if (m) { cache.set(id, m); return m }
  }
  const rows = ICONS[id] ?? ICONS.coin // (an unknown name must not take the page down)
  const c = document.createElement('canvas')
  c.width = 10
  c.height = 10
  const ctx = c.getContext('2d')!
  for (let y = 0; y < 10; y++) {
    for (let x = 0; x < 10; x++) {
      const col = COLORS[rows[y][x]]
      if (!col) continue
      ctx.fillStyle = col
      ctx.fillRect(x, y, 1, 1)
    }
  }
  url = c.toDataURL()
  cache.set(id, url)
  return url
}
